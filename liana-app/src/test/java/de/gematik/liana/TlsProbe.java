package de.gematik.liana;

import de.gematik.liana.crypto.CryptoProviders;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.net.InetAddress;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.GeneralSecurityException;
import java.security.KeyStore;
import java.security.SecureRandom;
import java.security.cert.X509Certificate;
import javax.net.ssl.KeyManager;
import javax.net.ssl.KeyManagerFactory;
import javax.net.ssl.SSLContext;
import javax.net.ssl.SSLSession;
import javax.net.ssl.SSLSocket;
import javax.net.ssl.TrustManager;
import javax.net.ssl.X509TrustManager;
import org.bouncycastle.jsse.BCSSLParameters;
import org.bouncycastle.jsse.BCSSLSocket;

/**
 * TLS client for tests against the HTTPS ports of LIANA: BCJSSE (like {@code
 * CryptoProviders.tls()}) with selectable protocols, groups and client certificate, or SunJSSE like
 * a Java Clientsystem without BouncyCastle. Trusts every server certificate; tests check the chain
 * themselves via {@link Result#session()}. Speaks HTTP/1.1 with {@code Connection: close}.
 */
public final class TlsProbe {

  /** PKCS#12 password of the test PKI from {@code tools/pki/konnektor-tls.sh}. */
  public static final String PASSWORD = "liana";

  private final boolean jdk;
  private Path clientP12;
  private String clientPassword = PASSWORD;
  private String[] protocols = {"TLSv1.2"};
  private String[] namedGroups;

  private TlsProbe(boolean jdk) {
    this.jdk = jdk;
  }

  /** BCJSSE, bound to BC. */
  public static TlsProbe bc() {
    return new TlsProbe(false);
  }

  /** SunJSSE of the JDK (no Brainpool). */
  public static TlsProbe jdk() {
    return new TlsProbe(true);
  }

  /** Client certificate from a PKCS#12 of the test PKI ({@link #PASSWORD}). */
  public TlsProbe clientCertificate(Path p12) {
    return clientCertificate(p12, PASSWORD);
  }

  /**
   * Client certificate from a PKCS#12 with its own password (e.g. generated by the KMS, LIANA-65).
   */
  public TlsProbe clientCertificate(Path p12, String password) {
    this.clientP12 = p12;
    this.clientPassword = password;
    return this;
  }

  public TlsProbe protocols(String... protocols) {
    this.protocols = protocols;
    return this;
  }

  /** Offered ECDHE groups (BCJSSE only). */
  public TlsProbe namedGroups(String... groups) {
    this.namedGroups = groups;
    return this;
  }

  public record Result(SSLSession session, String response) {

    public int status() {
      return Integer.parseInt(response.substring(9, 12));
    }

    public String body() {
      int start = response.indexOf("\r\n\r\n");
      return start < 0 ? "" : response.substring(start + 4);
    }

    public X509Certificate serverCertificate() throws IOException {
      return (X509Certificate) session.getPeerCertificates()[0];
    }
  }

  public Result get(int port, String path) throws IOException, GeneralSecurityException {
    return exchange(
        port, "GET " + path + " HTTP/1.1\r\nHost: localhost\r\nConnection: close\r\n\r\n");
  }

  /** POST with SOAP 1.1 ({@code text/xml}, {@code SOAPAction}). */
  public Result soap(int port, String path, String soapAction, String envelope)
      throws IOException, GeneralSecurityException {
    byte[] body = envelope.getBytes(StandardCharsets.UTF_8);
    return exchange(
        port,
        "POST "
            + path
            + " HTTP/1.1\r\nHost: localhost\r\nConnection: close\r\n"
            + "Content-Type: text/xml; charset=UTF-8\r\nSOAPAction: \""
            + soapAction
            + "\"\r\n"
            + "Content-Length: "
            + body.length
            + "\r\n\r\n"
            + envelope);
  }

  private Result exchange(int port, String request) throws IOException, GeneralSecurityException {
    try (var socket =
        (SSLSocket)
            context().getSocketFactory().createSocket(InetAddress.getLoopbackAddress(), port)) {
      socket.setSoTimeout(10_000);
      socket.setEnabledProtocols(protocols);
      if (namedGroups != null) {
        var bc = (BCSSLSocket) socket;
        BCSSLParameters parameters = bc.getParameters();
        parameters.setNamedGroups(namedGroups);
        bc.setParameters(parameters);
      }
      socket.startHandshake();
      OutputStream out = socket.getOutputStream();
      out.write(request.getBytes(StandardCharsets.UTF_8));
      out.flush();
      InputStream in = socket.getInputStream();
      ByteArrayOutputStream response = new ByteArrayOutputStream();
      in.transferTo(response);
      return new Result(socket.getSession(), response.toString(StandardCharsets.UTF_8));
    }
  }

  private SSLContext context() throws GeneralSecurityException, IOException {
    KeyManager[] keyManagers = null;
    if (clientP12 != null) {
      KeyStore store = KeyStore.getInstance("PKCS12", CryptoProviders.BC);
      try (InputStream in = Files.newInputStream(clientP12)) {
        store.load(in, clientPassword.toCharArray());
      }
      KeyManagerFactory factory =
          jdk
              ? KeyManagerFactory.getInstance("SunX509", "SunJSSE")
              : KeyManagerFactory.getInstance("PKIX", CryptoProviders.tls());
      factory.init(store, clientPassword.toCharArray());
      keyManagers = factory.getKeyManagers();
    }
    SSLContext context =
        jdk
            ? SSLContext.getInstance("TLS", "SunJSSE")
            : SSLContext.getInstance("TLS", CryptoProviders.tls());
    context.init(keyManagers, new TrustManager[] {new TrustAll()}, new SecureRandom());
    return context;
  }

  private static final class TrustAll implements X509TrustManager {
    @Override
    public void checkClientTrusted(X509Certificate[] chain, String authType) {}

    @Override
    public void checkServerTrusted(X509Certificate[] chain, String authType) {}

    @Override
    public X509Certificate[] getAcceptedIssuers() {
      return new X509Certificate[0];
    }
  }
}
