package de.gematik.liana.crypto;

import java.security.GeneralSecurityException;
import java.security.KeyPair;
import java.security.cert.CertificateException;
import java.security.cert.X509Certificate;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;
import java.util.concurrent.atomic.AtomicLong;
import javax.net.ssl.X509TrustManager;
import org.bouncycastle.asn1.x509.KeyPurposeId;

/**
 * ANCL_CCERT_LIST (TAB_KON_506-01) at runtime: certificates per Clientsystem, from the YAML ({@code
 * liana.tls.client-certs}, assigned to the first Clientsystem of the Informationsmodell), generated
 * by the Konnektor or imported (TIP1-A_4517-04, via the KMS, LIANA-65). LIANA keeps generated
 * certificates with their key as PKCS#12 for export. The TLS check ({@link #trustManager()}) sees
 * every state immediately; {@link #reset()} restores the YAML state.
 */
public final class ClientCertificates {

  /** One entry; {@code pkcs12} only for certificates generated by the Konnektor. */
  public record Entry(
      String internalId,
      String clientSystemId,
      X509Certificate certificate,
      String filename,
      byte[] pkcs12) {

    public boolean generated() {
      return pkcs12 != null;
    }
  }

  private final List<Entry> boot;
  private final AtomicLong ids = new AtomicLong();
  private volatile List<Entry> entries;

  /** {@code bootOwner}: Clientsystem that owns the certificates from the YAML. */
  public ClientCertificates(String bootOwner, List<X509Certificate> bootCertificates) {
    List<Entry> list = new ArrayList<>();
    for (X509Certificate certificate : bootCertificates) {
      list.add(new Entry(nextId(), bootOwner, certificate, null, null));
    }
    boot = List.copyOf(list);
    entries = boot;
  }

  private String nextId() {
    return "cert-" + ids.incrementAndGet();
  }

  public List<Entry> all() {
    return entries;
  }

  public List<Entry> of(String clientSystemId) {
    return entries.stream().filter(e -> e.clientSystemId().equals(clientSystemId)).toList();
  }

  public Optional<Entry> find(String clientSystemId, String internalId) {
    return of(clientSystemId).stream().filter(e -> e.internalId().equals(internalId)).findFirst();
  }

  /**
   * TIP1-A_4517-04: key pair and self-signed certificate (EKU clientAuth) for the Clientsystem, as
   * PKCS#12 with {@code password}; the certificate goes into ANCL_CCERT_LIST.
   */
  public synchronized Entry generate(
      String clientSystemId, TlsKeys.Algorithm algorithm, String password)
      throws GeneralSecurityException {
    KeyPair keys = TlsKeys.generate(algorithm);
    X509Certificate certificate =
        TlsKeys.selfSigned(
            keys, "Clientsystem " + clientSystemId, List.of(), KeyPurposeId.id_kp_clientAuth);
    byte[] p12 = TlsKeys.pkcs12(keys.getPrivate(), List.of(certificate), clientSystemId, password);
    return add(new Entry(nextId(), clientSystemId, certificate, clientSystemId + ".p12", p12));
  }

  /** TIP1-A_4517-04, A_21811-05: imported certificate after checking against TAB_KON_866. */
  public synchronized Entry importCertificate(
      String clientSystemId, byte[] content, String filename) throws TlsKeys.RejectedKeyException {
    X509Certificate certificate = TlsKeys.certificate(content);
    TlsKeys.checkNew(certificate.getPublicKey());
    return add(new Entry(nextId(), clientSystemId, certificate, filename, null));
  }

  private Entry add(Entry entry) {
    List<Entry> list = new ArrayList<>(entries);
    list.add(entry);
    entries = List.copyOf(list);
    return entry;
  }

  public synchronized boolean remove(String clientSystemId, String internalId) {
    List<Entry> list = new ArrayList<>(entries);
    boolean removed =
        list.removeIf(
            e -> e.clientSystemId().equals(clientSystemId) && e.internalId().equals(internalId));
    entries = List.copyOf(list);
    return removed;
  }

  public synchronized void reset() {
    entries = boot;
  }

  /** TIP1-A_4516 against the current state of the list. */
  public X509TrustManager trustManager() {
    return new X509TrustManager() {
      private ClientCertificateList current() {
        return new ClientCertificateList(entries.stream().map(Entry::certificate).toList());
      }

      @Override
      public void checkClientTrusted(X509Certificate[] chain, String authType)
          throws CertificateException {
        current().checkClientTrusted(chain, authType);
      }

      @Override
      public void checkServerTrusted(X509Certificate[] chain, String authType)
          throws CertificateException {
        current().checkServerTrusted(chain, authType);
      }

      @Override
      public X509Certificate[] getAcceptedIssuers() {
        return current().getAcceptedIssuers();
      }
    };
  }
}
