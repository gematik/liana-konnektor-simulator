# Test PKI for the Konnektor TLS (LIANA-58): server identity ID.AK.AUT and Clientsystem certificates (ANCL_CCERT_LIST).
# Test material only, no TSL, no OCSP. Writes to support/pki/server/ and support/pki/clients/;
# afterwards, origin and fingerprints belong in the SOURCE.md of those directories.
#
#   tools/pki/konnektor-tls.sh          regenerate everything
#   tools/pki/konnektor-tls.sh --rsa    only ID.AK.AUT RSA (LIANA-65)
set -euo pipefail

cd "$(dirname "$0")/../.."
SERVER=support/pki/server
CLIENTS=support/pki/clients
PASS=liana                      # PKCS#12 password of all containers (test material, not a secret)
DAYS=1826                       # A_24483: 5 years for TLS certificates
mkdir -p "$SERVER" "$CLIENTS"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

key() { # <curve> <file>
  openssl genpkey -algorithm EC -pkeyopt ec_paramgen_curve:"$1" -pkeyopt ec_param_enc:named_curve -out "$2"
}

# ID.AK.AUT RSA-2048 like C.AK.AUT.R2048 on the gSMC-K: server identity when TLS_USE_ECC_FOR_CS is off (LIANA-65);
# --rsa creates only this one and leaves the CA and the other identities unchanged
rsa_identity() {
  openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 -out "$tmp/ak-aut-rsa.key.pem"
  openssl req -new -key "$tmp/ak-aut-rsa.key.pem" -subj "/C=DE/O=LIANA NOT-VALID/CN=LIANA ID.AK.AUT rsa TEST-ONLY" \
    -out "$tmp/ak-aut-rsa.csr"
  openssl x509 -req -in "$tmp/ak-aut-rsa.csr" -CA "$SERVER/komp-ca.pem" -CAkey "$SERVER/komp-ca.key.pem" \
    -set_serial "0x$(openssl rand -hex 8)" -sha256 -days "$DAYS" -out "$SERVER/ak-aut-rsa.pem" \
    -extfile <(printf '%s\n' "basicConstraints=critical,CA:FALSE" "keyUsage=critical,digitalSignature,keyEncipherment" \
      "extendedKeyUsage=clientAuth,serverAuth" "subjectAltName=DNS:liana,DNS:localhost,IP:127.0.0.1")
  openssl pkcs12 -export -inkey "$tmp/ak-aut-rsa.key.pem" -in "$SERVER/ak-aut-rsa.pem" \
    -certfile "$SERVER/komp-ca.pem" -name ak-aut -passout "pass:$PASS" -out "$SERVER/ak-aut-rsa.p12"
  printf '%s  %s  bis %s\n' "$SERVER/ak-aut-rsa.pem" \
    "$(openssl x509 -in "$SERVER/ak-aut-rsa.pem" -noout -fingerprint -sha256 | cut -d= -f2)" \
    "$(openssl x509 -in "$SERVER/ak-aut-rsa.pem" -noout -enddate | cut -d= -f2)"
}
if [[ ${1:-} == --rsa ]]; then rsa_identity; exit 0; fi

# Component CA (role of the Komp-CA that issues C.AK.AUT)
key P-256 "$SERVER/komp-ca.key.pem"
openssl req -x509 -new -key "$SERVER/komp-ca.key.pem" -sha256 -days 3652 \
  -subj "/C=DE/O=LIANA NOT-VALID/CN=LIANA Komp-CA TEST-ONLY" \
  -addext "basicConstraints=critical,CA:TRUE" -addext "keyUsage=critical,keyCertSign,cRLSign" \
  -out "$SERVER/komp-ca.pem"

# ID.AK.AUT: brainpoolP256r1 as on the gSMC-K, P-256 as generated or imported per TAB_KON_866;
# EKU clientAuth and serverAuth per Tab_PKI_243 (clientAuth for CETP to the Ereignissenke, TIP1-A_4595, LIANA-59)
for variant in p256:P-256 bp256:brainpoolP256r1; do
  name=${variant%%:*}; curve=${variant#*:}
  key "$curve" "$tmp/ak-aut-$name.key.pem"
  openssl req -new -key "$tmp/ak-aut-$name.key.pem" -subj "/C=DE/O=LIANA NOT-VALID/CN=LIANA ID.AK.AUT $name TEST-ONLY" \
    -out "$tmp/ak-aut-$name.csr"
  openssl x509 -req -in "$tmp/ak-aut-$name.csr" -CA "$SERVER/komp-ca.pem" -CAkey "$SERVER/komp-ca.key.pem" \
    -set_serial "0x$(openssl rand -hex 8)" -sha256 -days "$DAYS" -out "$SERVER/ak-aut-$name.pem" \
    -extfile <(printf '%s\n' "basicConstraints=critical,CA:FALSE" "keyUsage=critical,digitalSignature" \
      "extendedKeyUsage=clientAuth,serverAuth" "subjectAltName=DNS:liana,DNS:localhost,IP:127.0.0.1")
  openssl pkcs12 -export -inkey "$tmp/ak-aut-$name.key.pem" -in "$SERVER/ak-aut-$name.pem" \
    -certfile "$SERVER/komp-ca.pem" -name ak-aut -passout "pass:$PASS" -out "$SERVER/ak-aut-$name.p12"
done

rsa_identity

# Clientsystem CS1: self-signed, as generated by the Konnektor (TIP1-A_4517-04) or imported
for variant in p256:P-256 bp256:brainpoolP256r1; do
  name=${variant%%:*}; curve=${variant#*:}
  key "$curve" "$tmp/cs1-$name.key.pem"
  openssl req -x509 -new -key "$tmp/cs1-$name.key.pem" -sha256 -days "$DAYS" \
    -subj "/C=DE/O=LIANA NOT-VALID/CN=LIANA Clientsystem CS1 $name TEST-ONLY" \
    -addext "basicConstraints=critical,CA:FALSE" -addext "keyUsage=critical,digitalSignature" \
    -addext "extendedKeyUsage=clientAuth" -out "$CLIENTS/cs1-$name.pem"
  openssl pkcs12 -export -inkey "$tmp/cs1-$name.key.pem" -in "$CLIENTS/cs1-$name.pem" -name cs1 \
    -passout "pass:$PASS" -out "$CLIENTS/cs1-$name.p12"
done

for f in "$SERVER"/*.pem "$CLIENTS"/*.pem; do
  case "$f" in *.key.pem) continue ;; esac
  printf '%s  %s  bis %s\n' "$f" "$(openssl x509 -in "$f" -noout -fingerprint -sha256 | cut -d= -f2)" \
    "$(openssl x509 -in "$f" -noout -enddate | cut -d= -f2)"
done
